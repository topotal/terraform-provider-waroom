var (
	_ resource.Resource                = &PostmortemTemplateResource{}
	_ resource.ResourceWithConfigure   = &PostmortemTemplateResource{}
	_ resource.ResourceWithImportState = &PostmortemTemplateResource{}
)

// NewPostmortemTemplateResource is a helper to simplify provider implementation.
func NewPostmortemTemplateResource() resource.Resource {
	return &PostmortemTemplateResource{}
}

// PostmortemTemplateResource is the resource implementation.
type PostmortemTemplateResource struct {
	client *waroom.Client
}

// PostmortemTemplateResourceModel describes the resource data model.
type PostmortemTemplateResourceModel struct {
	Id        types.String `tfsdk:"id"`
	UUID      types.String `tfsdk:"uuid"`
	Title     types.String `tfsdk:"title"`
	Blob      types.String `tfsdk:"blob"`
	CreatedAt types.String `tfsdk:"created_at"`
	UpdatedAt types.String `tfsdk:"updated_at"`
}

// Metadata returns the resource type name.
func (r *PostmortemTemplateResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_postmortem_template"
}

func (r *PostmortemTemplateResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	client, ok := req.ProviderData.(*waroom.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *Client, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}
	r.client = client
}

