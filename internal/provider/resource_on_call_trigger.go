var (
	_ resource.Resource                = &OnCallTriggerResource{}
	_ resource.ResourceWithConfigure   = &OnCallTriggerResource{}
	_ resource.ResourceWithImportState = &OnCallTriggerResource{}
)

const (
	onCallTriggerDefaultEventType    = "incident_created"
	onCallTriggerDefaultSourceFilter = "integration"
	onCallTriggerMaxRetryCount       = 10
)

var (
	onCallTriggerSeverities = []string{"critical", "high", "low", "info", "unknown"}
	onCallTriggerSources    = []string{"integration", "slack", "web"}
)

// NewOnCallTriggerResource is a helper to simplify provider implementation.
func NewOnCallTriggerResource() resource.Resource {
	return &OnCallTriggerResource{}
}

// OnCallTriggerResource is the resource implementation.
type OnCallTriggerResource struct {
	client *waroom.Client
}

// OnCallTriggerResourceModel describes the resource data model.
type OnCallTriggerResourceModel struct {
	Id                    types.String `tfsdk:"id"`
	UUID                  types.String `tfsdk:"uuid"`
	Name                  types.String `tfsdk:"name"`
	ServiceName           types.String `tfsdk:"service_name"`
	EscalationPolicyUUIDs types.Set    `tfsdk:"escalation_policy_uuids"`
	SeverityFilters       types.Set    `tfsdk:"severity_filters"`
	SourceFilters         types.Set    `tfsdk:"source_filters"`
	Enabled               types.Bool   `tfsdk:"enabled"`
	EventType             types.String `tfsdk:"event_type"`
	RetryCount            types.Int64  `tfsdk:"retry_count"`
}

// onCallTriggerResourceValues holds the set attributes of the model as Go values.
type onCallTriggerResourceValues struct {
	EscalationPolicyUUIDs []string
	SeverityFilters       []string
	SourceFilters         []string
}

// Metadata returns the resource type name.
func (r *OnCallTriggerResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_on_call_trigger"
}

func (r *OnCallTriggerResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}

	client, ok := req.ProviderData.(*waroom.Client)
	if !ok {
		resp.Diagnostics.AddError(
			"Unexpected Resource Configure Type",
			fmt.Sprintf("Expected *Client, got: %T. Please report this issue to the provider developers.", req.ProviderData),
		)
		return
	}
	r.client = client
}

// Schema defines the schema for the resource.
func (r *OnCallTriggerResource) Schema(_ context.Context, _ resource.SchemaRequest, resp *resource.SchemaResponse) {
	resp.Schema = schema.Schema{
		MarkdownDescription: "Manages a Waroom on-call trigger. " +
			"A trigger calls its escalation policies when an incident matching its filters is created in its service.\n\n" +
			"~> **Note:** A trigger is enabled by default (`enabled = true`), so once it is created, " +
			"incidents that match its filters page the on-call members of its escalation policies. " +
			"Set `enabled = false` to create it without paging anyone.",

		Attributes: map[string]schema.Attribute{
			"id": schema.StringAttribute{
				MarkdownDescription: "On-call trigger ID. This is an alias for `uuid`.",
				Computed:            true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"uuid": schema.StringAttribute{
				MarkdownDescription: "The unique identifier (UUID) of the trigger. This is automatically generated by Waroom.",
				Computed:            true,
				PlanModifiers: []planmodifier.String{
					stringplanmodifier.UseStateForUnknown(),
				},
			},
			"name": schema.StringAttribute{
				MarkdownDescription: "The name of the trigger.",
				Required:            true,
				Validators: []validator.String{
					stringvalidator.LengthAtLeast(1),
				},
			},
			"service_name": schema.StringAttribute{
				MarkdownDescription: "The name of the service the trigger belongs to. Changing it moves the trigger to another service.",
				Required:            true,
				Validators: []validator.String{
					stringvalidator.LengthAtLeast(1),
				},
			},
			"escalation_policy_uuids": schema.SetAttribute{
				MarkdownDescription: "The UUIDs of the escalation policies the trigger calls. At least one is required.",
				ElementType:         types.StringType,
				Required:            true,
				Validators: []validator.Set{
					setvalidator.SizeAtLeast(1),
					setvalidator.ValueStringsAre(waroomvalidator.UUID()),
				},
			},
			"severity_filters": schema.SetAttribute{
				MarkdownDescription: "The incident severities the trigger applies to: `critical`, `high`, `low`, `info` or `unknown`. " +
					"An empty set (`[]`) matches every severity.",
				ElementType: types.StringType,
				Required:    true,
				Validators: []validator.Set{
					setvalidator.ValueStringsAre(stringvalidator.OneOf(onCallTriggerSeverities...)),
				},
			},
			"source_filters": schema.SetAttribute{
				MarkdownDescription: "The incident sources the trigger applies to: `integration`, `slack` or `web`. " +
					"Defaults to `[\"" + onCallTriggerDefaultSourceFilter + "\"]`. At least one is required: Waroom accepts an empty set, " +
					"but a trigger with no source never fires. " +
					"Use `enabled = false` to stop a trigger instead.",
				ElementType: types.StringType,
				Optional:    true,
				Computed:    true,
				Default: setdefault.StaticValue(types.SetValueMust(types.StringType, []attr.Value{
					types.StringValue(onCallTriggerDefaultSourceFilter),
				})),
				Validators: []validator.Set{
					// Waroom accepts [] but never fires such a trigger, unlike an empty severity_filters, which matches
					// every severity (https://github.com/topotal/waroom-client-go/issues/212). Relax this if the API changes.
					setvalidator.SizeAtLeast(1),
					setvalidator.ValueStringsAre(stringvalidator.OneOf(onCallTriggerSources...)),
				},
			},
			"enabled": schema.BoolAttribute{
				MarkdownDescription: "Whether the trigger is enabled. Defaults to `true`.",
				Optional:            true,
				Computed:            true,
				Default:             booldefault.StaticBool(true),
			},
			"event_type": schema.StringAttribute{
				MarkdownDescription: "The event that fires the trigger. Currently only `" + onCallTriggerDefaultEventType + "`, which is the default.",
				Optional:            true,
				Computed:            true,
				Default:             stringdefault.StaticString(onCallTriggerDefaultEventType),
				Validators: []validator.String{
					stringvalidator.OneOf(onCallTriggerDefaultEventType),
				},
			},
			"retry_count": schema.Int64Attribute{
				MarkdownDescription: fmt.Sprintf("How many times the escalation restarts from the beginning when no one responds (0 to %d). Defaults to `0`.", onCallTriggerMaxRetryCount),
				Optional:            true,
				Computed:            true,
				Default:             int64default.StaticInt64(0),
				Validators: []validator.Int64{
					int64validator.Between(0, onCallTriggerMaxRetryCount),
				},
			},
		},
	}
}

// Create creates the resource and sets the initial Terraform state.
func (r *OnCallTriggerResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan OnCallTriggerResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)
	if resp.Diagnostics.HasError() {
		return
	}

	values, diags := plan.expand(ctx)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	creq := waroom.CreateOnCallTriggerReq{
		Name:                  plan.Name.ValueString(),
		ServiceName:           plan.ServiceName.ValueString(),
		EscalationPolicyUuids: values.EscalationPolicyUUIDs,
		SeverityFilters:       make([]waroom.CreateOnCallTriggerSeverityFilter, 0, len(values.SeverityFilters)),
		SourceFilters:         make([]waroom.CreateOnCallTriggerSourceFilter, 0, len(values.SourceFilters)),
		Enabled:               waroom.NewOptBool(plan.Enabled.ValueBool()),
		EventType:             waroom.NewOptCreateOnCallTriggerEventType(waroom.CreateOnCallTriggerEventType(plan.EventType.ValueString())),
		RetryCount:            waroom.NewOptInt(int(plan.RetryCount.ValueInt64())),
	}
	for _, v := range values.SeverityFilters {
		creq.SeverityFilters = append(creq.SeverityFilters, waroom.CreateOnCallTriggerSeverityFilter(v))
	}
	for _, v := range values.SourceFilters {
		creq.SourceFilters = append(creq.SourceFilters, waroom.CreateOnCallTriggerSourceFilter(v))
	}

	created, err := r.client.OnCallTriggers.Create(ctx, creq)
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("CreateOnCallTrigger, got error: %s", err))
		return
	}

	// Save the ID first so that the trigger is tracked (and tainted) even if reading the response fails.
	// Otherwise a live trigger, which may page people, would be left outside Terraform.
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), created.UUID)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("uuid"), created.UUID)...)

	// The create response has the same shape as the get response.
	trigger, err := toOnCallTrigger(created)
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("CreateOnCallTrigger created the on-call trigger %s but returned an unexpected response: %s. Import it with this UUID to manage it.", created.UUID, err))
		return
	}

	state, diags := newOnCallTriggerResourceModel(ctx, trigger)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Info(ctx, "created on-call trigger", map[string]interface{}{
		"id":           state.Id.ValueString(),
		"uuid":         state.UUID.ValueString(),
		"name":         state.Name.ValueString(),
		"service_name": state.ServiceName.ValueString(),
	})

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Read refreshes the Terraform state with the latest data.
func (r *OnCallTriggerResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data OnCallTriggerResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	trigger, err := r.client.OnCallTriggers.Get(ctx, waroom.GetOnCallTriggerParams{UUID: data.UUID.ValueString()})
	if err != nil {
		var apiErr *waroom.APIError
		if errors.As(err, &apiErr) && apiErr.StatusCode == http.StatusNotFound {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("GetOnCallTrigger, got error: %s", err))
		return
	}

	state, diags := newOnCallTriggerResourceModel(ctx, trigger)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &state)...)
}

// Update updates the resource and sets the updated Terraform state on success.
//
// Every attribute is sent. The API replaces the arrays as a whole, which is what the sets in the plan describe.
func (r *OnCallTriggerResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var plan OnCallTriggerResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &plan)...)

	var state OnCallTriggerResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &state)...)

	if resp.Diagnostics.HasError() {
		return
	}

	values, diags := plan.expand(ctx)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	ureq := waroom.UpdateOnCallTriggerReq{
		Name:                  waroom.NewOptString(plan.Name.ValueString()),
		ServiceName:           waroom.NewOptString(plan.ServiceName.ValueString()),
		EscalationPolicyUuids: values.EscalationPolicyUUIDs,
		SeverityFilters:       make([]waroom.UpdateOnCallTriggerSeverityFilter, 0, len(values.SeverityFilters)),
		SourceFilters:         make([]waroom.UpdateOnCallTriggerSourceFilter, 0, len(values.SourceFilters)),
		Enabled:               waroom.NewOptBool(plan.Enabled.ValueBool()),
		EventType:             waroom.NewOptUpdateOnCallTriggerEventType(waroom.UpdateOnCallTriggerEventType(plan.EventType.ValueString())),
		RetryCount:            waroom.NewOptInt(int(plan.RetryCount.ValueInt64())),
	}
	for _, v := range values.SeverityFilters {
		ureq.SeverityFilters = append(ureq.SeverityFilters, waroom.UpdateOnCallTriggerSeverityFilter(v))
	}
	for _, v := range values.SourceFilters {
		ureq.SourceFilters = append(ureq.SourceFilters, waroom.UpdateOnCallTriggerSourceFilter(v))
	}

	updated, err := r.client.OnCallTriggers.Update(ctx, ureq, waroom.UpdateOnCallTriggerParams{UUID: state.UUID.ValueString()})
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("UpdateOnCallTrigger, got error: %s", err))
		return
	}

	// The update response has the same shape as the get response.
	trigger, err := toOnCallTrigger(updated)
	if err != nil {
		resp.Diagnostics.AddError("Client Error", fmt.Sprintf("UpdateOnCallTrigger, unexpected response: %s", err))
		return
	}

	newState, diags := newOnCallTriggerResourceModel(ctx, trigger)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	tflog.Info(ctx, "updated on-call trigger", map[string]interface{}{
		"id":           newState.Id.ValueString(),
		"uuid":         newState.UUID.ValueString(),
		"name":         newState.Name.ValueString(),
		"service_name": newState.ServiceName.ValueString(),
	})

	resp.Diagnostics.Append(resp.State.Set(ctx, &newState)...)
}

