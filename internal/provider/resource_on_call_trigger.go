// ImportState imports an existing on-call trigger into Terraform state.
//
// The import ID is the UUID of the trigger.
//
// Example:
//
//	terraform import waroom_on_call_trigger.example 123e4567-e89b-12d3-a456-426614174000
func (r *OnCallTriggerResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	if _, err := uuid.Parse(req.ID); err != nil {
		resp.Diagnostics.AddError(
			"Invalid Import ID",
			fmt.Sprintf("Expected the UUID of an on-call trigger. Got: %s", req.ID),
		)
		return
	}

	resource.ImportStatePassthroughID(ctx, path.Root("uuid"), req, resp)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), req.ID)...)
}

// expand converts the set attributes of the model into Go values.
func (m *OnCallTriggerResourceModel) expand(ctx context.Context) (onCallTriggerResourceValues, diag.Diagnostics) {
	var diags diag.Diagnostics
	values := onCallTriggerResourceValues{
		EscalationPolicyUUIDs: []string{},
		SeverityFilters:       []string{},
		SourceFilters:         []string{},
	}
	for _, s := range []struct {
		set types.Set
		dst *[]string
	}{
		{m.EscalationPolicyUUIDs, &values.EscalationPolicyUUIDs},
		{m.SeverityFilters, &values.SeverityFilters},
		{m.SourceFilters, &values.SourceFilters},
	} {
		if !s.set.IsNull() && !s.set.IsUnknown() {
			diags.Append(s.set.ElementsAs(ctx, s.dst, false)...)
		}
	}
	return values, diags
}

// toOnCallTrigger converts a create / update response into the get response type,
// which has the same JSON shape, so that a single mapping function can be used.
func toOnCallTrigger(v interface{ MarshalJSON() ([]byte, error) }) (*waroom.OnCallTrigger, error) {
	b, err := v.MarshalJSON()
	if err != nil {
		return nil, err
	}
	var trigger waroom.OnCallTrigger
	if err := trigger.UnmarshalJSON(b); err != nil {
		return nil, err
	}
	return &trigger, nil
}

// newOnCallTriggerResourceModel converts an API on-call trigger into the resource model.
func newOnCallTriggerResourceModel(ctx context.Context, t *waroom.OnCallTrigger) (OnCallTriggerResourceModel, diag.Diagnostics) {
	var diags diag.Diagnostics
	trigger := onCallTriggerFromGet(t)

	data := OnCallTriggerResourceModel{
		Id:          types.StringValue(trigger.UUID),
		UUID:        types.StringValue(trigger.UUID),
		Name:        types.StringValue(trigger.Name),
		ServiceName: types.StringValue(trigger.ServiceName),
		Enabled:     types.BoolValue(trigger.Enabled),
		EventType:   types.StringValue(trigger.EventType),
		RetryCount:  types.Int64Value(int64(trigger.RetryCount)),
	}

	policyUUIDs := make([]string, 0, len(trigger.EscalationPolicies))
	for _, p := range trigger.EscalationPolicies {
		policyUUIDs = append(policyUUIDs, p.UUID)
	}

	var d diag.Diagnostics
	data.EscalationPolicyUUIDs, d = types.SetValueFrom(ctx, types.StringType, policyUUIDs)
	diags.Append(d...)
	data.SeverityFilters, d = types.SetValueFrom(ctx, types.StringType, trigger.SeverityFilters)
	diags.Append(d...)
	data.SourceFilters, d = types.SetValueFrom(ctx, types.StringType, trigger.SourceFilters)
	diags.Append(d...)

	return data, diags
}
