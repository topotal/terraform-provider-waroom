// ImportState imports an existing service runbook rule into Terraform state.
//
// The import ID must be in the format: service_name,uuid
// where:
//   - service_name: The name of the Waroom service
//   - uuid: The UUID of the runbook rule (e.g., 123e4567-e89b-12d3-a456-426614174000)
//
// Example:
//
//	terraform import waroom_service_runbook_rule.example my-service,123e4567-e89b-12d3-a456-426614174000
func (r *ServiceRunbookRuleResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	serviceName, id, err := parseServiceRunbookRuleImportID(req.ID)
	if err != nil {
		resp.Diagnostics.AddError("Invalid Import ID", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("service_name"), serviceName)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("uuid"), id)...)
	resp.Diagnostics.Append(resp.State.SetAttribute(ctx, path.Root("id"), id)...)
}

// parseServiceRunbookRuleImportID splits an import ID of the form "service_name,uuid".
// The UUID is returned in canonical form (lowercase, hyphenated), as the API returns it.
func parseServiceRunbookRuleImportID(importID string) (string, string, error) {
	parts := strings.Split(importID, ",")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", fmt.Errorf("expected import ID format: service_name,uuid. Got: %s", importID)
	}
	id, err := uuid.Parse(parts[1])
	if err != nil {
		return "", "", fmt.Errorf("the UUID part of the import ID is not valid: %s", err)
	}
	return parts[0], id.String(), nil
}

// serviceRunbookRuleNamespaceValidators applies the runbook namespace rule shared with the waroom_runbook
// data source, and additionally requires the leading slash: the runbook rule API looks the runbook up by
// the namespace as given and answers "Runbook not found" without it.
func serviceRunbookRuleNamespaceValidators() []validator.String {
	return append(runbookNamespaceValidators(),
		stringvalidator.RegexMatches(
			regexp.MustCompile(`^/`),
			"must start with `/` (e.g. `/default`)",
		),
	)
}

func (m *ServiceRunbookRuleResourceModel) setFromAPI(id uuid.UUID, pattern, target string, priority int, runbookNamespace string, createdAt, updatedAt time.Time) {
	m.Id = types.StringValue(id.String())
	m.UUID = types.StringValue(id.String())
	m.Pattern = types.StringValue(pattern)
	m.Target = types.StringValue(target)
	m.Priority = types.Int64Value(int64(priority))
	m.RunbookNamespace = types.StringValue(runbookNamespace)
	m.CreatedAt = types.StringValue(createdAt.Format(time.RFC3339))
	m.UpdatedAt = types.StringValue(updatedAt.Format(time.RFC3339))
}
